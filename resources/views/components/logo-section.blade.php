    <!-- JAVASCRIPT -->
    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const showMoreBtn = document.getElementById('showMoreBtn');
            const hiddenPartners = document.querySelectorAll('.hidden-partner');
            const btnText = showMoreBtn.querySelector('.btn-text');
            const btnIcon = showMoreBtn.querySelector('.btn-icon');
            const partnersGrid = document.querySelector('.partners-grid');

            let isExpanded = false;
            let isAnimating = false;

            showMoreBtn.addEventListener('click', async function() {
                if (isAnimating) return;

                isAnimating = true;
                showMoreBtn.classList.add('loading');

                if (!isExpanded) {
                    // Show hidden partners with staggered animation
                    await showHiddenPartners();

                    // Update button text and icon
                    btnText.textContent = 'Show Less';
                    showMoreBtn.classList.add('active');
                    partnersGrid.classList.add('expanding');

                    // Smooth scroll to newly shown cards
                    setTimeout(() => {
                        hiddenPartners[0].scrollIntoView({
                            behavior: 'smooth',
                            block: 'start',
                            inline: 'nearest'
                        });
                    }, 300);
                } else {
                    // Hide partners with smooth animation
                    await hideHiddenPartners();

                    // Update button text and icon
                    btnText.textContent = 'Show All Brands';
                    showMoreBtn.classList.remove('active');
                    partnersGrid.classList.remove('expanding');

                    // Scroll to top of partners section
                    setTimeout(() => {
                        partnersGrid.scrollIntoView({
                            behavior: 'smooth',
                            block: 'start'
                        });
                    }, 200);
                }

                isExpanded = !isExpanded;
                showMoreBtn.classList.remove('loading');
                isAnimating = false;
            });

            async function showHiddenPartners() {
                return new Promise(resolve => {
                    let delay = 0;

                    hiddenPartners.forEach((partner, index) => {
                        setTimeout(() => {
                            partner.classList.remove('hidden-partner');
                            partner.classList.add('revealing');

                            // After animation completes
                            setTimeout(() => {
                                partner.classList.remove('revealing');
                            }, 600);
                        }, delay);

                        delay += 50; // 50ms stagger between each card
                    });

                    setTimeout(resolve, delay + 600);
                });
            }

            async function hideHiddenPartners() {
                return new Promise(resolve => {
                    let delay = 0;
                    const reversedPartners = Array.from(hiddenPartners).reverse();

                    reversedPartners.forEach((partner, index) => {
                        setTimeout(() => {
                            partner.classList.add('hiding');

                            // After animation completes, add hidden class back
                            setTimeout(() => {
                                partner.classList.remove('hiding');
                                partner.classList.add('hidden-partner');
                            }, 500);
                        }, delay);

                        delay += 40; // 40ms stagger between each card (reverse order)
                    });

                    setTimeout(resolve, delay + 500);
                });
            }

            // Add intersection observer for lazy loading
            const observerOptions = {
                root: null,
                rootMargin: '50px',
                threshold: 0.1
            };

            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.style.willChange = 'transform, opacity';
                    }
                });
            }, observerOptions);

            // Observe all partner cards
            document.querySelectorAll('.partner-card').forEach(card => {
                observer.observe(card);
            });
        });
    </script>

